const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {ChatService}=require('../electron/chat-service.cjs');
const {ChatStore}=require('../electron/chat-store.cjs');
const wait=async fn=>{for(let n=0;n<100;n++){if(fn())return;await new Promise(r=>setTimeout(r,5))}assert.fail('response did not settle')};
async function fixture(t,streamChat){
 const directory=fs.mkdtempSync(path.join(os.tmpdir(),'zq-tools-')),keys=new Map();
 const credentials={get:async id=>keys.get(id),set:async(id,key)=>keys.set(id,key),delete:async id=>keys.delete(id)};
 const service=new ChatService({directory,credentials,providerFactory:()=>({streamChat})});
 t.after(()=>{service.shutdown();fs.rmSync(directory,{recursive:true,force:true})});
 const connection=await service.saveConnection({provider:'openai',name:'Fixture',apiKey:'fixture-only'});
 const chat=service.createConversation({connectionId:connection.id,model:'gpt-5.5'});
 return {service,directory,chat,last:()=>service.conversation(chat.id).messages.at(-1),send:tools=>service.sendMessage({conversationId:chat.id,text:'Research this',tools})};
}
test('selected tools and activity reach native execution and survive reload',async t=>{
 let request;const f=await fixture(t,async args=>{request=args;args.onTool({id:'search1',kind:'web_search',status:'running',detail:'Looking up sources'});args.onTool({id:'search1',kind:'web_search',status:'complete'});args.onDelta({content:'Found it.'})});
 await f.send(['web_search']);await wait(()=>f.last().status==='complete');
 assert.deepEqual(request.tools,['web_search']);assert.doesNotMatch(request.messages[0].content,/have no tools/);
 const saved=new ChatStore(f.directory).load().conversations[0].messages;
 assert.deepEqual(saved[0].tools,['web_search']);assert.equal(saved[1].toolActivity[0].status,'complete');
 assert.equal(saved[1].toolActivity[0].detail,'Looking up sources');
});
test('unsupported, repeated and malformed tools reject before history changes',async t=>{
 const f=await fixture(t,async()=>assert.fail('must not send'));
 for(const tools of [['shell'],['web_search','web_search'],{},[null]])await assert.rejects(f.send(tools),/tool/i);
 assert.equal(f.service.conversation(f.chat.id).messages.length,0);
 f.service.configureConversation({id:f.chat.id,connectionId:f.chat.connectionId,model:'gpt-3.5-turbo'});
 await assert.rejects(f.send(['web_search']),/tool/i);
});
test('stopping settles tool activity and ignores late callbacks and files',async t=>{
 let args,done;const f=await fixture(t,a=>{args=a;a.onTool({id:'s',kind:'web_search',status:'running'});return new Promise(r=>done=r)});
 await f.send(['web_search']);await wait(()=>!!args);f.service.stop(f.chat.id);
 args.onTool({id:'s',kind:'web_search',status:'complete'});await args.onArtifact({name:'late.txt',mime:'text/plain',data:Buffer.from('late').toString('base64')});done();
 assert.equal(f.last().toolActivity[0].status,'stopped');assert.equal(f.last().generatedFiles,undefined);
});
test('generated file bytes persist locally but are absent from public snapshots',async t=>{
 const data=Buffer.from('private generated bytes').toString('base64');
 const f=await fixture(t,async a=>{await a.onArtifact({name:'report.txt',mime:'text/plain',data});a.onDelta({content:'Created report.'})});
 await f.send(['code_execution']);await wait(()=>f.last().status==='complete');
 const file=f.last().generatedFiles[0];assert.equal(file.data,data);
 assert.equal(f.service.snapshot().conversations[0].messages.at(-1).generatedFiles[0].data,undefined);
 assert.equal(new ChatStore(f.directory).load().conversations[0].messages.at(-1).generatedFiles[0].data,data);
 assert.equal(f.service.renameConversation({id:f.chat.id,title:'Renamed'}).messages.at(-1).generatedFiles[0].data,undefined);
 assert.equal(f.service.configureConversation({id:f.chat.id,connectionId:f.chat.connectionId,model:'gpt-5.5'}).messages.at(-1).generatedFiles[0].data,undefined);
 assert.equal(f.service.moveConversation({id:f.chat.id,projectId:null}).messages.at(-1).generatedFiles[0].data,undefined);
 assert.deepEqual(f.service.generatedFile({conversationId:f.chat.id,messageId:f.last().id,fileId:file.id}),file);
});
