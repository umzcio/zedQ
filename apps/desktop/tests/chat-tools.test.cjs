test('real provider factory streams hosted search through ChatService and saves final citations',async t=>{
 const f=await fixture(t,async()=>assert.fail('override should be replaced')),requests=[];
 const {createProvider}=require('../../../packages/providers/index.cjs');
 f.service.connections.factory=(provider,options)=>createProvider(provider,{...options,fetchImpl:async(url,options)=>{
  requests.push({url,body:JSON.parse(options.body)});
  const frames=[
   {type:'response.output_item.added',output_index:0,item:{type:'web_search_call',id:'ws1',status:'in_progress'}},
   {type:'response.output_text.delta',output_index:1,item_id:'m1',content_index:0,delta:'Verified answer'},
   {type:'response.completed',response:{status:'completed',output:[{type:'web_search_call',id:'ws1',status:'completed'},{type:'message',id:'m1',content:[{type:'output_text',text:'Verified answer',annotations:[{type:'url_citation',end_index:15,url:'https://example.com/source'}]}]}]}},
  ];return {status:200,body:new ReadableStream({start(c){for(const frame of frames)c.enqueue(Buffer.from(`data: ${JSON.stringify(frame)}\n\n`));c.close()}})};
 }});
 await f.send(['web_search']);await wait(()=>f.last().status!=='streaming');
 assert.equal(f.last().status,'complete');assert.equal(requests[0].url,'https://api.openai.com/v1/responses');
 assert.deepEqual(requests[0].body.tools.filter(tool=>tool.type!=='function'),[{type:'web_search'}]);
 assert.deepEqual(requests[0].body.tools.filter(tool=>tool.type==='function').map(tool=>tool.name),['request_user_input']);
 assert.equal(f.last().content,'Verified answer [1](<https://example.com/source>)');assert.equal(f.last().toolActivity[0].status,'complete');
});
